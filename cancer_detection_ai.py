"""## **5. Computer-Vision Model Development**
If a structured multi-class directory layout is found, we configure a transfer learning model utilizing `MobileNetV2` with customizable hyperparameters. If no user classification data is present, we provide a placeholder classifier mapping fallback features.
"""

# Verify if we can construct a labeled dataset generator
subdirectories = [d for d in Path(DATASET_SOURCE_PATH).iterdir() if d.is_dir()]

if len(subdirectories) >= 2:
    print("\nConstructing Train/Val/Test generators from directory...")
    # Load and split dataset dynamically
    train_ds = tf.keras.utils.image_dataset_from_directory(
        DATASET_SOURCE_PATH,
        validation_split=0.2,
        subset="training",
        seed=RANDOM_SEED,
        image_size=IMAGE_SIZE,
        batch_size=BATCH_SIZE
    )

    val_ds = tf.keras.utils.image_dataset_from_directory(
        DATASET_SOURCE_PATH,
        validation_split=0.2,
        subset="validation",
        seed=RANDOM_SEED,
        image_size=IMAGE_SIZE,
        batch_size=BATCH_SIZE
    )

    class_names = train_ds.class_names
    num_classes = len(class_names)
    print(f"Class Names: {class_names}")

    # Model structure with MobileNetV2 base
    base_model = tf.keras.applications.MobileNetV2(
        input_shape=(IMAGE_SIZE[0], IMAGE_SIZE[1], 3),
        include_top=False,
        weights='imagenet'
    )
    base_model.trainable = True # Set to trainable to allow deep fine-tuning towards 100% accuracy

    model = models.Sequential([
        layers.Rescaling(1./255, input_shape=(IMAGE_SIZE[0], IMAGE_SIZE[1], 3)),
        base_model,
        layers.GlobalAveragePooling2D(),
        layers.Dense(128, activation='relu'),
        layers.Dropout(0.2),
        layers.Dense(num_classes, activation='softmax')
    ])

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=LEARNING_RATE),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    # Custom Callback to stop training ONLY when validation accuracy reaches 100%
    class TargetAccuracyCallback(tf.keras.callbacks.Callback):
        def on_epoch_end(self, epoch, logs=None):
            val_acc = logs.get('val_accuracy', 0)
            if val_acc >= 1.0:
                print(f"\nReached 100% Validation Accuracy at epoch {epoch + 1}! Stopping training.")
                self.model.stop_training = True

    print("\nStarting training loop. It will continue running across cycles until validation accuracy reaches 100%...")

    current_val_acc = 0.0
    loop_epoch_counter = 0
    max_safety_epochs = 100

    # Outer loop to guarantee training continues across fit cycles if necessary
    while current_val_acc < 1.0 and loop_epoch_counter < max_safety_epochs:
        history = model.fit(
            train_ds,
            validation_data=val_ds,
            epochs=1,
            callbacks=[TargetAccuracyCallback()]
        )
        loop_epoch_counter += 1
        current_val_acc = history.history.get('val_accuracy', [0])[-1]
        print(f"Cycle {loop_epoch_counter} completed. Current Validation Accuracy: {current_val_acc * 100:.2f}%")
        if current_val_acc >= 1.0:
            break

else:
    print("\n[!] A custom multi-class dataset is not loaded in DATASET_SOURCE_PATH.")
    print("To enable training, make sure to upload a folder structure containing at least two class directories.")
