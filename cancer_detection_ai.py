import zipfile
import shutil
from pathlib import Path

def inspect_and_extract_dataset(zip_path=None, target_dir=DATASET_SOURCE_PATH):
    """
    Extracts and inspects the structure of the dataset.
    Returns structure details and validity status.
    """
    if zip_path and os.path.exists(zip_path):
        print(f"Extracting {zip_path} to {target_dir}...")
        with zipfile.ZipFile(zip_path, 'r') as zip_ref:
            zip_ref.extractall(target_dir)
        print("Extraction completed successfully.")

    path_obj = Path(target_dir)
    all_files = list(path_obj.rglob('*'))
    image_extensions = {'.png', '.jpg', '.jpeg', '.webp', '.bmp'}
    images_found = [f for f in all_files if f.suffix.lower() in image_extensions]

    if not images_found:
        print("\n[!] ERROR: No images found in the specified path!")
        print("Please upload a ZIP containing classes or standard image files, or mount Google Drive.")
        return False, [], {}

    print(f"\nTotal detected files: {len(all_files)}")
    print(f"Total detected images: {len(images_found)}")

    # Identify structural layout
    subdirs = [d for d in path_obj.iterdir() if d.is_dir()]
    structure_dict = {}

    # Layout 1: dataset/class_name/image.jpg
    if len(subdirs) > 0:
        print("\nDetected Structure Layout: Directory-based Class Divisions")
        for subdir in subdirs:
            class_images = [f for f in subdir.rglob('*') if f.suffix.lower() in image_extensions]
            structure_dict[subdir.name] = len(class_images)
            print(f" - Class Name: '{subdir.name}' | Images: {len(class_images)}")
    else:
        # Layout 2: Flat directory structure
        print("\nDetected Structure Layout: Flat directory (unlabeled or requires metadata csv)")
        structure_dict['unclassified'] = len(images_found)

    # Scan for Object Detection formats (YOLO/COCO annotations)
    txt_files = [f for f in all_files if f.suffix.lower() == '.txt']
    json_files = [f for f in all_files if f.suffix.lower() == '.json']
    if txt_files and any("classes.txt" in f.name or len(txt_files) > 5 for f in txt_files):
        print("\n[*] NOTICE: Found annotation .txt files suggesting a YOLO object detection format.")
        print("This notebook will parse them if you configure it for detection, otherwise default classification is run.")
    elif json_files and any("instances" in f.name or "coco" in f.name for f in json_files):
        print("\n[*] NOTICE: Found COCO layout json annotations.")

    return True, images_found, structure_dict

