"""## **4. Exploratory Data Analysis (EDA)**
We will visualize the distribution of shapes, report any corrupt image files, and analyze the balance of our image collection.
"""

def run_exploratory_analysis(image_paths):
    if not image_paths:
        print("No images loaded to analyze.")
        return

    widths = []
    heights = []
    corrupt_count = 0
    valid_images = []

    for img_path in image_paths[:200]: # Sample 200 images for speed
        try:
            with Image.open(img_path) as im:
                im.verify() # check integrity
            with Image.open(img_path) as im:
                w, h = im.size
                widths.append(w)
                heights.append(h)
                valid_images.append((img_path, w, h))
        except Exception:
            corrupt_count += 1

    print(f"\nCorrupt / Unreadable Images found in sample: {corrupt_count}")

    if widths and heights:
        fig, axes = plt.subplots(1, 2, figsize=(12, 5))
        sns.histplot(widths, ax=axes[0], color='skyblue', kde=True)
        axes[0].set_title("Image Width Distribution")
        axes[0].set_xlabel("Width (pixels)")

        sns.histplot(heights, ax=axes[1], color='salmon', kde=True)
        axes[1].set_title("Image Height Distribution")
        axes[1].set_xlabel("Height (pixels)")
        plt.tight_layout()
        plt.show()

        print("\n*EDA Insight*: The distribution plots describe the shape uniformity of the raw files.")
        print("Non-uniform distributions justify our target normalization during prep.")
    else:
        print("Could not compute image size distributions.")

